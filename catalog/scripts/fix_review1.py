SECTIONS = {'P16-03': ('B', 'コンパクション（cleanup.policy=compact）'), 'P05-02': ('C', '正常な操作：基準と重点の費用'), 'P12-03': ('B', 'B-7 マテリアライズドビューが追随するもの（ガイド Part 12）'), 'P07-05': ('B', 'B-3 DB のスキーマ変更（PostgreSQL 18、書き込みをかけ続ける）')}


def main():
    for p in sorted(glob.glob(os.path.join(CAT, 'decisions', 'd*.json'))):
        data = json.load(open(p, encoding='utf-8'))
        for k, d in data.items():
            if k in LINKS:
                d['meas']['links'] = LINKS[k]
            if k in PROPS:
                d['def']['properties'] = PROPS[k]
            if k in SECTIONS:
                t, sec = SECTIONS[k]
                lst = d['meas'].setdefault('sections', {}).setdefault(t, [])
                if sec not in lst:
                    lst.append(sec)
            if k in TARGET:
                d['def']['target'] = TARGET[k]
            for (kk, obj, field), text in SET.items():
                if kk == k:
                    d[obj][field] = text
            for kk, obj, field, old, new in REPLACE:
                if kk == k and new not in d[obj][field]:
                    if old not in d[obj][field]:
                        raise SystemExit('phrase not found in %s %s.%s' % (k, obj, field))
                    d[obj][field] = d[obj][field].replace(old, new)
            if k.startswith('P17-0') and 'sign' in d['def'] and int(k[4:]) <= 9:
                del d['def']['sign']          # 16: both signs of the step are now copied from Part 17's tables by merge.py
        json.dump(data, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('applied')


if __name__ == '__main__':
    main()
